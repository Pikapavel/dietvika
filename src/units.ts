/** Единицы USDA → порции для показа */
export function toDisplay(g: GroupId, usda: number): number {
  return usda * SYS.perUsda[g];
}
/** Порции для показа → единицы USDA (для записи в журнал) */
export function fromDisplay(g: GroupId, shown: number): number {
  return shown / SYS.perUsda[g];
}
export function portionHint(g: GroupId): string {
  return SYS.portion[g];
}
export function handLines(g: GroupId, veg = false): string[] {
  if (veg && g === "prot") return VEG_PROTEIN_HANDS;
  return SYS.hands[g];
}

