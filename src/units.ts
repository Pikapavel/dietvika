/** Мясо и рыба: в вегетарианском плане эти продукты не показываем (по началу названия) */
const MEAT_FISH = ["Курица", "Говядина", "Рыба", "Морепродукты", "Консервы рыбные", "Котлета", "Колбаса"];
/** Вегетарианские источники белка — первыми в списке */
const VEG_FIRST = ["Яйцо", "Тофу", "Орехи", "Семечки", "Арахис"];

export function isMeatOrFish(name: string): boolean {
  return MEAT_FISH.some((m) => name.startsWith(m));
}

/** Порядок продуктов белка для вегетарианского плана: без мяса и рыбы, вегетарианские — первыми */
export function vegProteinOrder<T extends { name: string }>(foods: T[]): T[] {
  const rank = (n: string) => {
    const i = VEG_FIRST.findIndex((v) => n.startsWith(v));
    return i < 0 ? VEG_FIRST.length : i;
  };
  return foods.filter((f) => !isMeatOrFish(f.name)).sort((a, b) => rank(a.name) - rank(b.name));
}

// ---------- форматирование ----------

/** Округление до четверти */
export function q4(n: number): number {
  return Math.round(n * 4) / 4;
}

/** 1.5 → "1 ½", 0.25 → "¼", 3 → "3" */
export function fmt(n: number): string {
  const v = q4(Math.max(0, n));
  const w = Math.floor(v);
  const r = v - w;
  const f = r === 0.25 ? "¼" : r === 0.5 ? "½" : r === 0.75 ? "¾" : "";
  if (!f) return String(w);
  return w ? `${w} ${f}` : f;
}

/** Склонение: plural(2, ["порция","порции","порций"]). Дробные — родительный ед. ч. («1 ½ порции») */
export function plural(n: number, forms: [string, string, string]): string {
  const v = q4(Math.abs(n));
  if (!Number.isInteger(v)) return forms[1];
  const m10 = v % 10, m100 = v % 100;
  if (m10 === 1 && m100 !== 11) return forms[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
  return forms[2];
}

export const PORTION: [string, string, string] = ["порция", "порции", "порций"];
export const GLASS: [string, string, string] = ["стакан", "стакана", "стаканов"];

/** "3 порции" */
export function portions(n: number): string {
  return `${fmt(n)} ${plural(n, PORTION)}`;
}

/** Винительный падеж: «отметить 1 порцию» */
export function portionsAcc(n: number): string {
  return `${fmt(n)} ${plural(n, ["порцию", "порции", "порций"])}`;
}

/** Глагол «остался/осталась/осталось» под число и род */
function left(n: number, gender: "m" | "f"): string {
  const v = q4(n);
  if (Number.isInteger(v) && v % 10 === 1 && v % 100 !== 11) return gender === "m" ? "Остался" : "Осталась";
  return "Осталось";
}

/** Подсказка «Что доесть»: сколько осталось и чем закрыть, языком рук. remainingUsda > 0.
 *  Для бобовых — остаток на неделю. */
export function nudgeText(g: GroupId, remainingUsda: number, veg = false): string {
  const n = q4(toDisplay(g, remainingUsda));
  const shown = fmt(n);
  switch (g) {
    case "fv":
      return `${left(n, "m")} ${shown} ${plural(n, ["кулак", "кулака", "кулаков"])} фруктов и овощей: например, яблоко, огурец с помидором, брокколи или горсть ягод. Разные цвета — лучше всего.`;
    case "leg":
      return `${left(n, "f")} ${shown} ${plural(n, PORTION)} бобовых на эту неделю: например, кулак нута в салат, суп из чечевицы или 4 ложки хумуса.`;
    case "grain":
      return `${left(n, "f")} ${shown} ${plural(n, ["горсть", "горсти", "горстей"])} зерновых или столько же ломтиков хлеба: например, гречка, овсянка или ржаной хлеб.`;
    case "prot": {
      if (veg) {
        const v = n < 1 ? "хватит одного яйца или маленькой горсти орехов." :
          `например, ${Math.ceil(n) > 3 ? "тофу (½ кулака ≈ 2 порции), яйца" : `${Math.ceil(n)} ${plural(Math.ceil(n), ["яйцо", "яйца", "яиц"])}, тофу`} или маленькая горсть орехов.`;
        return `${left(n, "f")} ${shown} ${plural(n, PORTION)} белка: ${v}`;
      }
      if (ACTIVE_SYSTEM === "usda" && n >= 2.5) {
        const palms = Math.round((n / 3) * 2) / 2;
        return `${left(palms, "f")} ${fmt(palms)} ${plural(palms, ["ладонь", "ладони", "ладоней"])} белка: например, курица, рыба или индейка.`;
      }
      if (n < 1) return `${left(n, "f")} ${shown} порции белка: хватит одного яйца или маленькой горсти орехов.`;
      const eggs = Math.ceil(n);
      return `${left(n, "f")} ${shown} ${plural(n, PORTION)} белка: например, ${eggs} ${plural(eggs, ["яйцо", "яйца", "яиц"])} или маленькая горсть орехов (1 порция).`;
    }
    case "dairy":
      return `${left(n, "m")} ${shown} ${plural(n, GLASS)} молочного: например, кефир или молоко. Или кусочек сыра, около 30 г.`;
  }
}

